#!/usr/bin/env python3
"""Developer-only 100-digit ABCD oracle; not a product/runtime dependency.

Run from the repository root and redirect stdout to
 tests/fixtures/transmission_line_oracle.hpp, then clang-format that header.
Inputs are exact binary64 values converted to mpmath, not decimal intentions.
"""
def main():
    import math
    import sys
    import mpmath as mp

    mp.mp.dps = 100
    rows = []
    minimum = float.fromhex('0x0.0000000000001p-1022')
    for zc, z0 in ((1e15, 50.), (50., 1e15), (100., 50.), (50., 50.),
                   (6.9e15, 50.), (50., 6.9e15)):
        for delay in (0., .125, .25, .375, .5, .625, .75, .875, 1., math.nextafter(.5, 0.),
                      math.nextafter(.5, 1.), math.nextafter(1., 0.),
                      math.nextafter(1., 2.), math.nextafter(.25, 0.),
                      math.nextafter(.25, 1.)):
            rows.append((zc, z0, delay, 0., 1.))
        for loss in (minimum, 4 * minimum, 1e-310, 1e-100, 1e-16, 1e-15,
                     1e-14, .5, 3., 6000., 6500., 10000.):
            for delay in (0., .5):
                rows.append((zc, z0, delay, loss, 1.))
        for loss in (1e-16, 1e-6, 3.):
            for delay in (math.nextafter(.25, 0.), math.nextafter(.25, 1.),
                          math.nextafter(.5, 0.), math.nextafter(.5, 1.)):
                rows.append((zc, z0, delay, loss, 1.))
        for frequency, delay in ((minimum, .125), (minimum, 1.), (1e-160, 1e-165),
                                 (1e-100, 1.), (1., 1e-99), (.125, .25), (1., .3)):
            rows.append((zc, z0, delay, 0., frequency))

    print('// Generated by scripts/reference/generate-transmission-line-oracle.py (mpmath, 100 digits).')
    print('// Independent ABCD hyperbolic formulation; exact binary64 input values.')
    print('#pragma once\n#include <array>\n')
    print('struct TransmissionLineOracle {\n    double zc, z0, delay, loss, frequency;\n    double reflection_real, reflection_imag, transmission_real, transmission_imag;\n};')
    print(f'inline constexpr std::array<TransmissionLineOracle, {len(rows)}> transmission_line_oracle{{{{')
    for row in rows:
        zc, z0, delay, loss, frequency = map(mp.mpf, row)
        alpha = loss * mp.log(10) / 20
        turns = frequency * delay
        cosine, sine = mp.cospi(2 * turns), mp.sinpi(2 * turns)
        a = mp.cosh(alpha) * cosine + 1j * mp.sinh(alpha) * sine
        h = mp.sinh(alpha) * cosine + 1j * mp.cosh(alpha) * sine
        b, c = (zc / z0) * h, (z0 / zc) * h
        denominator = 2 * a + b + c
        r, t = (b - c) / denominator, 2 / denominator
        values = row + (float(r.real), float(r.imag), float(t.real), float(t.imag))
        print('    {' + ', '.join(repr(value) for value in values) + '},')
    print('}};')
    print(f'Generated {len(rows)} independent ABCD cases with mpmath {mp.__version__}.', file=sys.stderr)


if __name__ == "__main__":
    main()
